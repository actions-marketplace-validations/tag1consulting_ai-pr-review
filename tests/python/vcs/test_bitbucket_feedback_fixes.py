def _finding(text: str = "sql injection", *, ood: bool = False, sev: str = "High") -> Finding:
    return Finding(
        severity="Low" if ood else sev, confidence=90, finding=text,
        file="app.py", line=4, out_of_diff=ood,
    )


def _render(**kw: object) -> str:
    base: dict[str, object] = dict(
        existing_body=f"{build_summary_marker('abc', hidden=True)}\nFirst",
        findings=[_finding()], event="REQUEST_CHANGES", failed_agents=[],
        agent_prompt="", id_map={}, prior_id_map={}, workspace="ws",
        repo_slug="repo", head_sha=_HEAD,
    )
    base.update(kw)
    return _render_combined_body(**base)  # type: ignore[arg-type]


# --- Fix 1: doubled Summary heading ---------------------------------------


@pytest.mark.parametrize(
    "text",
    ["## Summary\n\nBody", "### Summary\nBody", "# Summary:\n\nBody", "## **Summary**\n\nBody"],
)
def test_strip_leading_summary_heading_any_level(text: str) -> None:
    assert strip_leading_summary_heading(text) == "Body"


def test_strip_leading_summary_heading_leaves_other_text() -> None:
    assert strip_leading_summary_heading("Intro\n## Summary\nBody") == "Intro\n## Summary\nBody"
    assert strip_leading_summary_heading("## Summary of changes\nBody") == "## Summary of changes\nBody"
    assert strip_leading_summary_heading("Body only") == "Body only"
    # Only one heading is removed.
    assert strip_leading_summary_heading("## Summary\n## Summary\nB") == "## Summary\nB"


def test_first_run_body_renders_one_summary_heading() -> None:
    first_run = f"{build_summary_marker('abc', hidden=True)}\n## Summary\n\nAdds foo.\n\n---\n*AI Review — generated by x*"
    body = _render(existing_body=first_run)
    assert "### Summary\nAdds foo." in body
    assert "## Summary" not in body.replace("### Summary", "")


def test_already_posted_doubled_heading_heals_on_next_run() -> None:
    doubled = (
        f"{build_summary_marker('abc', hidden=True)}\n## AI Review Findings\n\n"
        "**Findings:** 1\n\n### Findings\n- x\n\n### Summary\n## Summary\n\nAdds foo.\n"
    )
    assert _extract_walkthrough(doubled) == "Adds foo."
    body = _render(existing_body=doubled)
    assert body.count("Summary") == 1


# --- Fix 2: annotation note --------------------------------------------------


@pytest.mark.parametrize(
    ("count", "verb"), [(1, "is"), (2, "are")]
)
def test_annotation_note_after_list_plural_and_verb(count: int, verb: str) -> None:
    body = _render(annotated_count=count)
    note = f"{count} of the findings listed here {verb} also shown as inline Code Insights"
    assert note in body
    assert "above" not in body
    assert body.index("sql injection") < body.index(note)
    assert body.index("### Findings") < body.index(note)


def test_annotation_note_not_carried_into_walkthrough() -> None:
    body = _render(annotated_count=1, existing_body=(
        f"{build_summary_marker('abc', hidden=True)}\n## Summary\n\nAdds foo."
    ))
    assert _extract_walkthrough(body) == "Adds foo."


