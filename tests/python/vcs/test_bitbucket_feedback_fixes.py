# --- Fix 4 and 5: provider-level --------------------------------------------


def _provider(
    *,
    user_status: int = 200,
    verdicts: bool = False,
    post_response: httpx.Response | None = None,
    existing_comments: bool = True,
) -> tuple[BitbucketProvider, dict]:
    captured: dict = {}
    created: dict = {}
    existing = {
        "id": 100,
        "content": {"raw": f"{SUMMARY_MARKER_PREFIX} sha={_HEAD} -->\n## Summary\n\nAdds foo."},
        "user": {"account_id": _BOT},
    }

    def handler(req: httpx.Request) -> httpx.Response:
        path = req.url.path.rstrip("/")
        if req.method == "GET" and path.endswith("/user"):
            if user_status >= 400:
                return httpx.Response(user_status, text="forbidden")
            return httpx.Response(200, json={"account_id": _BOT})
        if req.method == "GET" and path.endswith("/comments/101"):
            return httpx.Response(200, json=created)
        if req.method == "GET":
            return httpx.Response(200, json={"values": [existing] if existing_comments else []})
        if req.method == "POST" and path.endswith("/comments") and post_response is not None:
            return post_response
        if req.method == "POST" and path.endswith("/comments"):
            # Fail-closed identity => no existing summary => a new comment.
            created.update(
                id=101, content={"raw": json.loads(req.content)["content"]["raw"]},
                user={"account_id": _BOT},
            )
            return httpx.Response(201, json=created)
        if req.method == "PUT" and "/comments/" in path:
            captured["body"] = json.loads(req.content)["content"]["raw"]
            return httpx.Response(200, json={"id": int(path.rsplit("/", 1)[1])})
        return httpx.Response(200, json={})

    client = RecordingClient(
        http=httpx.Client(
            transport=httpx.MockTransport(handler),
            base_url="https://api.bitbucket.org/2.0",
        ),
        recorder=TapeRecorder(record_dir=None),
        retry_policy=RetryPolicy(attempts=1, base_backoff=0, jitter=False, sleep=lambda _s: None),
    )
    prov = BitbucketProvider(
        config=BitbucketConfig(
            workspace="ws", repo_slug="repo", pr_id=7, email="x@y", api_token="t",
            verdicts=verdicts,
        ),
        client=client,
    )
    return prov, captured


def test_identity_failure_logs_warning_with_status_and_shows_notice(
    caplog: pytest.LogCaptureFixture,
) -> None:
    prov, captured = _provider(user_status=403)
    with caplog.at_level(logging.WARNING, logger="ai_pr_review.vcs.bitbucket"):
        summary = prov.post_summary("## Summary\n\nAdds foo.", _HEAD)
        assert summary.created
        result = prov.post_findings(
            [_finding()], DiffContext(diff_text=_DIFF, head_sha=_HEAD), event="COMMENT",
            summary_comment_id=summary.comment_id,
        )
        assert result.ok, result.error
    warnings = [r.getMessage() for r in caplog.records if "could not resolve the bot" in r.getMessage()]
    assert len(warnings) == 1
    assert "HTTP 403" in warnings[0]
    assert "Account:Read" in warnings[0]
    assert "Bot account not verified" in captured["body"]


def test_identity_failure_still_fails_closed() -> None:
    prov, _ = _provider(user_status=403)
    assert prov._list_summary_comments() == []


def test_identity_ok_has_no_warning_or_notice(caplog: pytest.LogCaptureFixture) -> None:
    prov, captured = _provider()
    with caplog.at_level(logging.WARNING, logger="ai_pr_review.vcs.bitbucket"):
        prov.post_findings(
            [_finding()], DiffContext(diff_text=_DIFF, head_sha=_HEAD), event="COMMENT"
        )
    assert not [r for r in caplog.records if "could not resolve the bot" in r.getMessage()]
    assert "Bot account not verified" not in captured["body"]


def test_dismiss_help_line_only_when_verdicts_enabled() -> None:
    prov_on, cap_on = _provider(verdicts=True)
    prov_on.post_findings([_finding()], DiffContext(diff_text=_DIFF, head_sha=_HEAD), event="COMMENT")
    assert "bitbucket-setup#dismissing-findings" in cap_on["body"]
    footer_at = cap_on["body"].index("\n---\n*AI Review")
    assert cap_on["body"].index("bitbucket-setup#dismissing-findings") < footer_at

    prov_off, cap_off = _provider(verdicts=False)
    prov_off.post_findings([_finding()], DiffContext(diff_text=_DIFF, head_sha=_HEAD), event="COMMENT")
    assert "dismissing-findings" not in cap_off["body"]


